"""List the frontend files the service worker saves for offline use (frontend/sw-files.js).

Run after adding, removing or renaming frontend files:  python scripts/make_offline_manifest.py
scripts/package_release.py runs it too, so a published release is always complete.
"""
from hashlib import sha256
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / "frontend"
OUTPUT = WEB / "sw-files.js"
TEXT = {".html", ".js", ".css", ".json", ".svg"}
SKIP_NAMES = {"sw.js", "sw-files.js"}
# The opening video is streamed, not stored: offline the app simply starts without it.
SKIP_SUFFIXES = {".mp4", ".webm", ".mov"}


def offline_files() -> list[Path]:
    files = [p for p in WEB.rglob("*") if p.is_file() and "tests" not in p.relative_to(WEB).parts
             and p.name not in SKIP_NAMES and p.suffix.lower() not in SKIP_SUFFIXES]
    source = "\n".join(p.read_text(encoding="utf-8", errors="ignore") for p in files if p.suffix.lower() in TEXT)
    # public/ holds design references too: only what the app really uses is stored.
    return sorted(p for p in files if p.relative_to(WEB).parts[0] != "public" or p.name in source)


def write() -> Path:
    files = offline_files()
    digest = sha256()
    for path in files:
        digest.update(path.relative_to(WEB).as_posix().encode())
        digest.update(path.read_bytes().replace(b"\r\n", b"\n") if path.suffix.lower() in TEXT else path.read_bytes())
    names = ["./"] + [p.relative_to(WEB).as_posix() for p in files]
    lines = ",\n".join(f'  "{n}"' for n in names)
    OUTPUT.write_text(
        "/* Generated by scripts/make_offline_manifest.py. Do not edit by hand. */\n"
        f'self.COOPER_BUILD = "{digest.hexdigest()[:12]}";\n'
        f"self.COOPER_FILES = [\n{lines}\n];\n", encoding="utf-8", newline="\n")
    return OUTPUT


if __name__ == "__main__":
    out = write()
    size = sum(p.stat().st_size for p in offline_files()) / 1e6
    print(f"{out.relative_to(ROOT).as_posix()}: {len(offline_files())} files, {size:.1f} MB")
